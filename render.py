_MISSING = (0x1F, 0x11, 0x11, 0x11, 0x11, 0x11, 0x1F)  # box for unknown chars


def text_width(text, scale):
    """Pixel width of text at the given integer scale (1px tracking)."""
    return len(text) * 6 * scale - scale


def wrap_text(text, max_width_px, scale):
    """Word-wrap text to lines fitting max_width_px. Returns list of lines."""
    max_chars = max(1, (max_width_px + scale) // (6 * scale))
    words = text.split(' ')
    lines = []
    cur = ''
    for w in words:
        if len(w) > max_chars:  # hard-split a very long word
            if cur:
                lines.append(cur)
                cur = ''
            while len(w) > max_chars:
                lines.append(w[:max_chars])
                w = w[max_chars:]
            cur = w
            continue
        trial = w if not cur else cur + ' ' + w
        if len(trial) <= max_chars:
            cur = trial
        else:
            lines.append(cur)
            cur = w
    if cur:
        lines.append(cur)
    return lines


# -------------------------------------------------------------- canvas ----
class Canvas:
    """RGB canvas backed by a bytearray; origin top-left."""

    def __init__(self, width, height, bg):
        self.w = width
        self.h = height
        self.px = bytearray(width * height * 3)
        self.fill(bg)

    def fill(self, color):
        r, g, b = color
        self.px[:] = bytes((r, g, b)) * (self.w * self.h)

    def set_pixel(self, x, y, color):
        if 0 <= x < self.w and 0 <= y < self.h:
            i = (y * self.w + x) * 3
            self.px[i], self.px[i + 1], self.px[i + 2] = color

    def fill_rect(self, x, y, w, h, color):
        x0 = max(0, x)
        y0 = max(0, y)
        x1 = min(self.w, x + w)
        y1 = min(self.h, y + h)
        if x1 <= x0 or y1 <= y0:
            return
        r, g, b = color
        row = bytes((r, g, b)) * (x1 - x0)
        for yy in range(y0, y1):
            i = (yy * self.w + x0) * 3
            self.px[i:i + len(row)] = row

    def hline(self, x, y, w, color, thick=1):
        self.fill_rect(x, y, w, thick, color)

    def vline(self, x, y, h, color, thick=1):
        self.fill_rect(x, y, thick, h, color)

    def rect(self, x, y, w, h, color, thick=1):
        self.hline(x, y, w, color, thick)
        self.hline(x, y + h - thick, w, color, thick)
        self.vline(x, y, h, color, thick)
        self.vline(x + w - thick, y, h, color, thick)

    def draw_char(self, ch, x, y, scale, color):
        glyph = _FONT.get(ch, _MISSING)
        for row in range(7):
            bits = glyph[row]
            for col in range(5):
                if bits & (1 << (4 - col)):
                    self.fill_rect(x + col * scale, y + row * scale,
                                   scale, scale, color)

    def draw_text(self, text, x, y, scale, color):
        cx = x
        for ch in text:
            self.draw_char(ch, cx, y, scale, color)
            cx += 6 * scale
        return cx

    def draw_text_centered(self, text, cx, y, scale, color):
        w = text_width(text, scale)
        return self.draw_text(text, cx - w // 2, y, scale, color)

    def draw_wrapped(self, text, x, y, max_w, scale, color, line_h=None):
        """Draw wrapped text; returns y just below the last line."""
        if line_h is None:
            line_h = 7 * scale + 2
        yy = y
        for line in wrap_text(text, max_w, scale):
            self.draw_text(line, x, yy, scale, color)
            yy += line_h
        return yy


# ------------------------------------------------------------------ png ----
def _chunk(kind, data):
    out = struct.pack('>I', len(data)) + kind + data
    out += struct.pack('>I', zlib.crc32(kind + data) & 0xFFFFFFFF)
    return out


def save_png(canvas, path):
    """Write the canvas as a deterministic true-colour PNG."""
    w, h = canvas.w, canvas.h
    raw = bytearray()
    stride = w * 3
    for y in range(h):
        raw.append(0)  # filter: none
        raw += canvas.px[y * stride:(y + 1) * stride]
    ihdr = struct.pack('>IIBBBBB', w, h, 8, 2, 0, 0, 0)
    data = (b'\x89PNG\r\n\x1a\n'
            + _chunk(b'IHDR', ihdr)
            + _chunk(b'IDAT', zlib.compress(bytes(raw), 9))
            + _chunk(b'IEND', b''))
    with open(path, 'wb') as f:
        f.write(data)
    return len(data)
